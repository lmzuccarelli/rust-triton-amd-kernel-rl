/// Write the wrapped string buffer to `src/inference/generated_prompt.rs`.
///
/// Returns the number of bytes written on success.
pub fn write_generated_prompt() -> io::Result<usize> {
    write_generated_prompt_to("src/inference/generated_prompts.rs")
}

/// Escape `{`/`}` so literal artifact text survives being embedded inside a
/// `format!` template in the generated source.
///
/// The Triton code examples in the optimization database contain Python dict
/// literals (e.g. `triton.Config({"BLOCK_M": 128})`); without escaping, those
/// braces would be parsed as `format!` arguments and fail to compile.
fn escape_braces(input: &str) -> String {
    input.replace('{', "{{").replace('}', "}}")
}

/// Write the wrapped string buffer to an arbitrary path (handy for tests).
pub fn write_generated_prompt_to<P: AsRef<Path>>(path: P) -> io::Result<usize> {
    // This artifact is substituted into a `format!(...)` string in the
    // generated source, so any literal braces it contains must be escaped.
    let available_optimizations =
        escape_braces(&create_available_optimizations(DEFAULT_PATH).map_err(io::Error::other)?);
    // `performance_state_category` is substituted into a plain raw string
    // (`get_performance_state_category`), so it must NOT be brace-escaped.
    let performance_state_category =
        create_performance_state_category(DEFAULT_PATH).map_err(io::Error::other)?;
    // The markdown database is substituted into a `format!(...)` string
    // (`get_task_generate_code_prompt`), so its braces must be escaped. The
    // generated state categories are injected at the marker line.
    let database_md = fs::read_to_string("artifacts/optimization_database.md")?;
    let optimization_database = escape_braces(&database_md.replace(
        PERFORMANCE_STATE_CATEGORIES_MARKER,
        &performance_state_category,
    ));

    let version = env!("CARGO_PKG_VERSION");

    let result = GENERATED_PROMPT_SOURCE
        .replace("{version}", version)
        .replace("{avalaible_optimizations}", &available_optimizations)
        .replace("{performance_state_category}", &performance_state_category)
        .replace("{optimization_database}", &optimization_database);

    fs::write(&path, &result)?;
    Ok(result.len())
}
